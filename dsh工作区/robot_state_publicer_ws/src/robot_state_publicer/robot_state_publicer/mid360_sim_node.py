#!/usr/bin/env python3
"""Simulated Livox Mid-360 LiDAR + IMU publisher.

Publishes driver-compatible PointCloud2 data and sensor_msgs/Imu at the
requested topics.  The point cloud is generated by ray-casting a simple
indoor scene (see scan.py), so consumers receive a usable 3D scan instead
of an empty or random placeholder.
"""

from __future__ import annotations

import time

import rclpy
from geometry_msgs.msg import TransformStamped
from builtin_interfaces.msg import Time as TimeMsg
from rclpy.callback_groups import MutuallyExclusiveCallbackGroup
from rclpy.executors import MultiThreadedExecutor
from rclpy.node import Node
from rosgraph_msgs.msg import Clock
from rclpy.qos import HistoryPolicy, QoSProfile, ReliabilityPolicy
from sensor_msgs.msg import Imu, PointCloud2, PointField
from tf2_ros import StaticTransformBroadcaster

import numpy as np

from robot_state_publicer.scan import generate_scan

# packed layout of livox_ros_driver2::LivoxPointXyzrtlt
POINT_DTYPE = np.dtype([
    ("x", "<f4"),
    ("y", "<f4"),
    ("z", "<f4"),
    ("intensity", "<f4"),
    ("tag", "u1"),
    ("line", "u1"),
    ("timestamp", "<f8"),
])
assert POINT_DTYPE.itemsize == 26


def make_pointcloud2(scan: dict, stamp, frame_id: str, stamp_ns: int) -> PointCloud2:
    count = int(scan["x"].size)
    points = np.empty(count, dtype=POINT_DTYPE)
    points["x"] = scan["x"]
    points["y"] = scan["y"]
    points["z"] = scan["z"]
    points["intensity"] = scan["intensity"]
    points["tag"] = scan["tag"]
    points["line"] = scan["line"]
    points["timestamp"] = float(stamp_ns) + scan["offset_ns"]

    msg = PointCloud2()
    msg.header.stamp = stamp
    msg.header.frame_id = frame_id
    msg.height = 1
    msg.width = count
    msg.fields = [
        PointField(name="x", offset=0, datatype=PointField.FLOAT32, count=1),
        PointField(name="y", offset=4, datatype=PointField.FLOAT32, count=1),
        PointField(name="z", offset=8, datatype=PointField.FLOAT32, count=1),
        PointField(name="intensity", offset=12, datatype=PointField.FLOAT32, count=1),
        PointField(name="tag", offset=16, datatype=PointField.UINT8, count=1),
        PointField(name="line", offset=17, datatype=PointField.UINT8, count=1),
        PointField(name="timestamp", offset=18, datatype=PointField.FLOAT64, count=1),
    ]
    msg.is_bigendian = False
    msg.point_step = POINT_DTYPE.itemsize
    msg.row_step = msg.point_step * count
    msg.data = points.tobytes()
    msg.is_dense = True
    return msg


class Mid360SimNode(Node):
    def __init__(self) -> None:
        super().__init__("mid360_sim")

        self.declare_parameter("lidar_topic", "/livox/lidar")
        self.declare_parameter("lidar_alias_topic", "/livix/lidar")
        self.declare_parameter("imu_topic", "/livox/imu")
        self.declare_parameter("frame_id", "livox_frame")
        self.declare_parameter("lidar_rate", 10.0)
        self.declare_parameter("imu_rate", 200.0)
        self.declare_parameter("points_per_frame", 20000)
        self.declare_parameter("max_range", 40.0)
        self.declare_parameter("lidar_height", 0.27)
        self.declare_parameter("publish_tf", True)
        self.declare_parameter("publish_alias", True)
        self.declare_parameter("base_frame", "base_link")
        self.declare_parameter("seed", 1)
        # 用 /clock（Gazebo 仿真时间）给消息打时间戳，但定时器按真实时间运行。
        # 原因：Gazebo 的 /clock 只有约 10 Hz，若 use_sim_time=true，ROS 定时器会被
        # 时钟跳变限制到 ~10-20 Hz，IMU 无法达到标称 200 Hz（2026-11-17 实测）。
        # 打开该选项后：定时器 wall-time 驱动，消息/静态 TF 的时间戳用 /clock 插值，
        # 既保证高频率又让时间戳与 Gazebo 仿真时间一致。
        self.declare_parameter("stamp_from_sim_clock", True)

        self.lidar_topic = str(self.get_parameter("lidar_topic").value)
        self.alias_topic = str(self.get_parameter("lidar_alias_topic").value)
        self.imu_topic = str(self.get_parameter("imu_topic").value)
        self.frame_id = str(self.get_parameter("frame_id").value)
        self.lidar_rate = float(self.get_parameter("lidar_rate").value)
        self.imu_rate = float(self.get_parameter("imu_rate").value)
        self.points_per_frame = int(self.get_parameter("points_per_frame").value)
        self.max_range = float(self.get_parameter("max_range").value)
        self.lidar_height = float(self.get_parameter("lidar_height").value)
        self.publish_tf = bool(self.get_parameter("publish_tf").value)
        self.publish_alias = bool(self.get_parameter("publish_alias").value)
        self.base_frame = str(self.get_parameter("base_frame").value)
        self.seed = int(self.get_parameter("seed").value)
        self.stamp_from_sim_clock = bool(self.get_parameter("stamp_from_sim_clock").value)
        self._sim_ns = 0
        self._sim_mono_ns = 0
        self._sim_clock_ok = False

        if self.lidar_rate <= 0.0 or self.imu_rate <= 0.0:
            raise ValueError("lidar_rate and imu_rate must be positive")
        if self.points_per_frame <= 0:
            raise ValueError("points_per_frame must be positive")

        qos = QoSProfile(
            history=HistoryPolicy.KEEP_LAST,
            depth=5,
            reliability=ReliabilityPolicy.RELIABLE,
        )
        self.lidar_pub = self.create_publisher(PointCloud2, self.lidar_topic, qos)
        self.alias_pub = None
        if self.publish_alias and self.alias_topic and self.alias_topic != self.lidar_topic:
            self.alias_pub = self.create_publisher(PointCloud2, self.alias_topic, qos)

        imu_qos = QoSProfile(
            history=HistoryPolicy.KEEP_LAST,
            depth=50,
            reliability=ReliabilityPolicy.RELIABLE,
        )
        self.imu_pub = self.create_publisher(Imu, self.imu_topic, imu_qos)

        if self.stamp_from_sim_clock:
            clock_qos = QoSProfile(
                history=HistoryPolicy.KEEP_LAST,
                depth=10,
                reliability=ReliabilityPolicy.BEST_EFFORT,
            )
            self.create_subscription(Clock, "/clock", self._on_clock, clock_qos)

        self._rng = np.random.default_rng(self.seed + 1000000)
        self._frame_index = 0
        self._tf_broadcaster = None
        if self.publish_tf:
            self._tf_broadcaster = StaticTransformBroadcaster(self)
            self._publish_static_tf()

        # 点云生成（2 万点射线求交）是重计算，若与 IMU 定时器共用单线程执行器，
        # IMU 会被点云回调"饿死"（实测只有 ~20 Hz）。这里分到两个回调组，并在
        # main() 里用 MultiThreadedExecutor，保证 IMU 接近标称 200 Hz。
        self._lidar_group = MutuallyExclusiveCallbackGroup()
        self._imu_group = MutuallyExclusiveCallbackGroup()
        self.create_timer(
            1.0 / self.lidar_rate, self._publish_lidar, callback_group=self._lidar_group
        )
        self.create_timer(
            1.0 / self.imu_rate, self._publish_imu, callback_group=self._imu_group
        )

        self.get_logger().info(
            f"Mid-360 simulator: {self.points_per_frame} pts @ {self.lidar_rate:.0f} Hz "
            f"on {self.lidar_topic}"
            + (f" (+ alias {self.alias_topic})" if self.alias_pub else "")
            + f", IMU {self.imu_rate:.0f} Hz on {self.imu_topic}, "
            f"frame={self.frame_id}"
        )

    def _on_clock(self, msg: Clock) -> None:
        self._sim_ns = int(msg.clock.sec) * 1_000_000_000 + int(msg.clock.nanosec)
        self._sim_mono_ns = time.monotonic_ns()
        self._sim_clock_ok = True

    def _stamp(self) -> TimeMsg:
        """消息时间戳：优先用 /clock 插值（仿真时间），否则用节点时钟。"""
        if self.stamp_from_sim_clock and self._sim_clock_ok:
            elapsed = time.monotonic_ns() - self._sim_mono_ns
            ns = self._sim_ns + max(elapsed, 0)
            return TimeMsg(sec=int(ns // 1_000_000_000), nanosec=int(ns % 1_000_000_000))
        now = self.get_clock().now().to_msg()
        return TimeMsg(sec=now.sec, nanosec=now.nanosec)

    def _publish_static_tf(self) -> None:
        t = TransformStamped()
        t.header.stamp = self._stamp()
        t.header.frame_id = self.base_frame
        t.child_frame_id = self.frame_id
        t.transform.translation.x = 0.0
        t.transform.translation.y = 0.0
        t.transform.translation.z = self.lidar_height
        self._tf_broadcaster.sendTransform(t)

    def _publish_lidar(self) -> None:
        stamp = self._stamp()
        scan = generate_scan(
            points_per_frame=self.points_per_frame,
            lidar_height=self.lidar_height,
            seed=self.seed + self._frame_index,
            max_range=self.max_range,
            lidar_rate=self.lidar_rate,
        )
        stamp_ns = int(stamp.sec) * 1_000_000_000 + int(stamp.nanosec)
        msg = make_pointcloud2(scan, stamp, self.frame_id, stamp_ns)
        self.lidar_pub.publish(msg)
        if self.alias_pub is not None:
            self.alias_pub.publish(msg)
        self._frame_index += 1

    def _publish_imu(self) -> None:
        msg = Imu()
        msg.header.stamp = self._stamp()
        msg.header.frame_id = self.frame_id

        # No orientation estimate from the raw Mid-360 IMU.
        msg.orientation.w = 1.0
        msg.orientation_covariance[0] = -1.0

        msg.angular_velocity.x = float(self._rng.normal(0.0, 0.001))
        msg.angular_velocity.y = float(self._rng.normal(0.0, 0.001))
        msg.angular_velocity.z = float(self._rng.normal(0.0, 0.001))
        msg.linear_acceleration.x = float(self._rng.normal(0.0, 0.02))
        msg.linear_acceleration.y = float(self._rng.normal(0.0, 0.02))
        msg.linear_acceleration.z = float(9.80665 + self._rng.normal(0.0, 0.02))

        for i in (0, 4, 8):
            msg.angular_velocity_covariance[i] = 1e-6
            msg.linear_acceleration_covariance[i] = 4e-4

        self.imu_pub.publish(msg)

    def destroy_node(self) -> bool:
        return super().destroy_node()


def main(args=None) -> None:
    rclpy.init(args=args)
    node = Mid360SimNode()
    # 多线程执行器：点云生成与 IMU 发布互不阻塞（见 __init__ 中的回调组说明）。
    executor = MultiThreadedExecutor(num_threads=2)
    executor.add_node(node)
    try:
        executor.spin()
    except KeyboardInterrupt:
        pass
    finally:
        executor.shutdown()
        node.destroy_node()
        rclpy.shutdown()


if __name__ == "__main__":
    main()
